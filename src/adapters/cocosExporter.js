import fs from 'fs';
import path from 'path';

/**
 * 将提取出来的游戏资源和数值配置，自动封装并输出为标准的 Cocos Creator 3.x 项目工程
 */
export async function exportToCocosProject(assetManifest, gameConfig, targetOutputDir) {
  fs.mkdirSync(targetOutputDir, { recursive: true });

  const cocosDirs = [
    path.join(targetOutputDir, 'assets', 'textures'),
    path.join(targetOutputDir, 'assets', 'audio'),
    path.join(targetOutputDir, 'assets', 'scripts'),
    path.join(targetOutputDir, 'assets', 'scenes')
  ];
  cocosDirs.forEach(d => fs.mkdirSync(d, { recursive: true }));

  // 1. 生成 Cocos 标准 project.json
  const projectJson = {
    "engine": "cocos-creator-js",
    "packages": "packages",
    "name": path.basename(targetOutputDir),
    "id": "gea-port-" + Date.now(),
    "version": "3.8.0",
    "isNew": false
  };
  fs.writeFileSync(path.join(targetOutputDir, 'project.json'), JSON.stringify(projectJson, null, 2));

  // 2. 生成 package.json 与 tsconfig.json
  const pkgJson = {
    "name": path.basename(targetOutputDir),
    "version": "1.0.0",
    "description": "Ported and restructured via GEA (Game Engineer Anything)",
    "dependencies": {}
  };
  fs.writeFileSync(path.join(targetOutputDir, 'package.json'), JSON.stringify(pkgJson, null, 2));

  const tsConfig = {
    "compilerOptions": {
      "module": "commonjs",
      "lib": ["dom", "es2015", "es2017"],
      "target": "es2017",
      "experimentalDecorators": true,
      "skipLibCheck": true,
      "strict": false
    },
    "include": ["assets/**/*"]
  };
  fs.writeFileSync(path.join(targetOutputDir, 'tsconfig.json'), JSON.stringify(tsConfig, null, 2));

  // 3. 拷贝美术贴图与音频
  if (assetManifest && assetManifest.textures) {
    assetManifest.textures.forEach(t => {
      if (fs.existsSync(t.path)) {
        fs.copyFileSync(t.path, path.join(targetOutputDir, 'assets', 'textures', t.name));
      }
    });
  }
  if (assetManifest && assetManifest.audios) {
    assetManifest.audios.forEach(a => {
      if (fs.existsSync(a.path)) {
        fs.copyFileSync(a.path, path.join(targetOutputDir, 'assets', 'audio', a.name));
      }
    });
  }

  // 4. 生成 TypeScript 配置定义
  const configTs = `/**
 * Generated by GEA (Game Engineer Anything)
 * Reverse-engineered configuration table
 */
export const GAME_EXTRACTED_CONFIG = ${JSON.stringify(gameConfig || {}, null, 2)};
`;
  fs.writeFileSync(path.join(targetOutputDir, 'assets', 'scripts', 'GameConfig.ts'), configTs);

  // 5. 生成主控制器模板 MainController.ts
  const controllerTs = `import { _decorator, Component, Node } from 'cc';
const { ccclass, property } = _decorator;
import { GAME_EXTRACTED_CONFIG } from './GameConfig';

@ccclass('MainController')
export class MainController extends Component {
    start() {
        console.log('[GEA] Cocos Creator Game Initialized with extracted configs:', GAME_EXTRACTED_CONFIG);
    }

    update(deltaTime: number) {
        // Main game loop
    }
}
`;
  fs.writeFileSync(path.join(targetOutputDir, 'assets', 'scripts', 'MainController.ts'), controllerTs);

  return {
    success: true,
    targetDirectory: targetOutputDir,
    texturesCopied: assetManifest?.textures?.length || 0,
    audioCopied: assetManifest?.audios?.length || 0
  };
}
